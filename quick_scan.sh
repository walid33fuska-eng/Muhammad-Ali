#!/bin/bash

echo "فحص المنافذ على الخوادم المكتشفة..."
echo "====================================="

# خوادم البريد المكتشفة
for ip in 194.204.217.65 194.204.217.205 194.204.217.173 81.192.44.133 41.248.240.121; do
  echo ""
  echo "[*] فحص: $ip"
  
  # منافذ البريد الشائعة
  for port in 25 80 443 465 587 993 995; do
    timeout 2 bash -c "echo >/dev/tcp/$ip/$port" 2>/dev/null
    if [ $? -eq 0 ]; then
      echo "  ✓ Port $port مفتوح"
    fi
  done
done

echo ""
echo "====================================="
echo "إذا ظهر أي Port مفتوح، يمكنك استغلاله"
echo "====================================="
